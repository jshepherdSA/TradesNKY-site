import type { MetadataRoute } from "next";

const SITE_URL = "https://tradesnky.org";

/**
 * AI crawlers we explicitly welcome. The wildcard rule below already allows
 * them, but listing them by name makes the intent to permit AI/LLM crawling
 * unambiguous even if a default ever changes.
 */
const AI_CRAWLERS = [
  "GPTBot",
  "ChatGPT-User",
  "OAI-SearchBot",
  "ClaudeBot",
  "anthropic-ai",
  "Claude-Web",
  "PerplexityBot",
  "Google-Extended",
  "Applebot-Extended",
  "CCBot",
];

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      { userAgent: "*", allow: "/" },
      ...AI_CRAWLERS.map((userAgent) => ({ userAgent, allow: "/" })),
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
